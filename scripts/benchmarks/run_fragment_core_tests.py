#!/usr/bin/env python3
"""Guarded local synthetic prototype tests, no models/downloads/runtime changes.

Use an existing Python environment with pytest+psutil. All generated bytes stay
under this clone and the private pytest basetemp is removed on exit. Refuse to
run unless CPU6 is available. Budget includes clone, reports and test bytes.
"""
import argparse
import json
import os
import resource
from pathlib import Path
import shutil
import subprocess
import sys
import time

import psutil

ROOT = Path(__file__).resolve().parents[2]
REPORT = ROOT / 'reports/audio-fragment-core'
TEMP = ROOT / '.fragment-core-testtmp'
BUDGET = 96 * 1024 ** 2
RSS_LIMIT = 512 * 1024 ** 2
DISK_RESERVE = int(5.5 * 1024 ** 3)
RAM_RESERVE = 2 * 1024 ** 3


def tree_bytes():
    total = 0
    for path in ROOT.rglob('*'):
        try:
            if path.is_file() and not path.is_symlink():
                total += path.stat().st_size
        except FileNotFoundError:
            pass  # A test may delete its own bounded temporary file.
    return total


def child_limits():
    # Hard address-space limit also bounds child RSS between monitor samples.
    # Leave32MiB for this lightweight supervisor; tree RSS is checked separately.
    limit = RSS_LIMIT - 32 * 1024 ** 2
    resource.setrlimit(resource.RLIMIT_AS, (limit, limit))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('tests', nargs='*', default=['tests/test_fragment_core.py'])
    parser.add_argument('--label', default='focused')
    parser.add_argument('--hard-address-space', action='store_true',
                        help='480MiB child virtual-address cap for pure Python tests; inherited by subprocesses')
    args = parser.parse_args()
    if not args.label.replace('-', '').isalnum():
        raise ValueError('Use a simple label')
    if TEMP.exists():
        raise RuntimeError('Private basetemp already exists; inspect it before another run')
    process = psutil.Process()
    if 6 not in process.cpu_affinity():
        raise RuntimeError('CPU6 is not available')
    process.cpu_affinity([6])
    before_bytes = tree_bytes()
    if before_bytes > BUDGET:
        raise RuntimeError('Clone already exceeds96MiB budget')
    before_disk = shutil.disk_usage(ROOT).free
    before_ram = psutil.virtual_memory().available
    if before_disk < DISK_RESERVE + (BUDGET - before_bytes) or before_ram < RAM_RESERVE:
        raise RuntimeError('Insufficient disk/RAM reserve including possible new writes')
    REPORT.mkdir(parents=True, exist_ok=True)
    results = REPORT / 'matrix'
    results.mkdir(exist_ok=True)
    env = dict(os.environ, OMP_NUM_THREADS='1', OMP_THREAD_LIMIT='1', OPENBLAS_NUM_THREADS='1',
               MKL_NUM_THREADS='1', NUMEXPR_NUM_THREADS='1', PYTHONDONTWRITEBYTECODE='1',
               PYTEST_DISABLE_PLUGIN_AUTOLOAD='1', FRAGMENT_RESULTS_DIR=str(results))
    command = [sys.executable, '-m', 'pytest', '-q', '-p', 'no:cacheprovider',
               '--basetemp', str(TEMP), f'--junitxml={REPORT / (args.label + ".xml")}', *args.tests]
    stats = dict(command=command, cpu_affinity=[6], no_models=True,
                 memory_monitor='explicit supervisor + known Popen PID + psutil PPid descendants; fail-closed permission errors', baseline_bytes=before_bytes,
                 disk_free_before=before_disk, memory_available_before=before_ram,
                 peak_rss_bytes=0, peak_workspace_bytes=before_bytes, minimum_disk_free=before_disk,
                 minimum_memory_available=before_ram, limits=dict(workspace_bytes=BUDGET,
                 process_tree_rss_bytes=RSS_LIMIT, child_address_space_bytes=RSS_LIMIT - 32 * 1024 ** 2 if args.hard_address_space else None, disk_free_bytes=DISK_RESERVE, memory_available_bytes=RAM_RESERVE))
    began = time.monotonic()
    child = None
    try:
        with (REPORT / (args.label + '.log')).open('w') as output:
            child = subprocess.Popen(command, cwd=ROOT, env=env, stdout=output, stderr=subprocess.STDOUT,
                                     preexec_fn=child_limits if args.hard_address_space else None)
            while child.poll() is None:
                # Always sample the known Popen PID explicitly. psutil7.2.2
                # recursive children uses /proc/*/stat PPid scans, and raises
                # AccessDenied rather than silently losing inaccessible trees.
                processes = [process] + process.children(recursive=True)
                try:
                    processes.append(psutil.Process(child.pid))
                except psutil.NoSuchProcess:
                    if child.poll() is None:
                        raise RuntimeError('Known running child PID unavailable to RSS guard')
                processes = list({member.pid: member for member in processes}.values())
                rss = 0
                for member in processes:
                    try:
                        rss += member.memory_info().rss
                    except psutil.NoSuchProcess:
                        pass
                used, disk, ram = tree_bytes(), shutil.disk_usage(ROOT).free, psutil.virtual_memory().available
                stats['peak_rss_bytes'] = max(stats['peak_rss_bytes'], rss)
                stats['peak_workspace_bytes'] = max(stats['peak_workspace_bytes'], used)
                stats['minimum_disk_free'] = min(stats['minimum_disk_free'], disk)
                stats['minimum_memory_available'] = min(stats['minimum_memory_available'], ram)
                if time.monotonic() - began > 270:
                    raise TimeoutError('Focused tests exceeded270-second watchdog')
                if rss > RSS_LIMIT or used > BUDGET or disk < DISK_RESERVE or ram < RAM_RESERVE:
                    raise RuntimeError('Resource guard breached; stopping only this test process tree')
                time.sleep(.15)
            stats['exit_code'] = child.returncode
    except BaseException as exc:
        stats['error'] = f'{type(exc).__name__}: {exc}'
        if child and child.poll() is None:
            for descendant in psutil.Process(child.pid).children(recursive=True):
                descendant.kill()
            child.kill()
            child.wait()
        raise
    finally:
        stats['elapsed_seconds'] = time.monotonic() - began
        if TEMP.exists():
            shutil.rmtree(TEMP)
        stats['private_basetemp_removed'] = not TEMP.exists()
        stats['final_workspace_bytes'] = tree_bytes()
        (REPORT / (args.label + '-resources.json')).write_text(json.dumps(stats, indent=2) + '\n')
    print((REPORT / (args.label + '.log')).read_text())
    print(json.dumps(stats, indent=2))
    return child.returncode


if __name__ == '__main__':
    sys.exit(main())
