"""V2 fixture generation only; no core/matcher import or feature computation."""
from array import array
import math
import random
import sys


def round_ratio(numerator, denominator):
    return (1 if numerator >= 0 else -1) * ((abs(numerator) + denominator // 2) // denominator)


def encode(values):
    data = array('h', values)
    if sys.byteorder != 'little':
        data.byteswap()
    return data.tobytes()


def make_fixture(case):
    rate, channels = case['rate'], case['channels']
    count = rate * case['source_seconds'] + case['extra_frames']
    cut = rate * case['cut_seconds'] + case['cut_extra_frames']
    overlap = (rate * case['overlap_ms'] + 999) // 1000
    kind = case['kind']
    if kind == 'failed_anchor':
        right = b'\0\0' * (30 * rate)
        return [right[:-2] + b'\1\0', right], [0], None
    # Integer symbol blocks are balanced but reshuffled independently, never
    # interpreted as speech. Fixed tone LUT is frozen via generated byte hashes.
    per_channel = []
    for channel in range(channels):
        rng = random.Random(case['seed'] + channel)
        symbols = [2 * i - (case['levels'] - 1) for i in range(case['levels'])]
        repeated = list(symbols)
        rng.shuffle(repeated)
        block = []
        samples = []
        for i in range(count):
            if not block:
                block = list(symbols)
                rng.shuffle(block)
            value = block.pop()
            if kind == 'uniform':
                value = rng.randrange(-12000, 12001)
            elif kind in ('tone', 'tone_jitter'):
                value = round(32 * math.sin(2 * math.pi * (i % 40) / 40))
                if kind == 'tone_jitter':
                    value += rng.randrange(-1, 2)
            elif kind == 'repeated_block':
                value = repeated[i % len(repeated)]
            elif kind == 'extrema':
                value = -32768 if i % 2 == 0 else 32767
            elif kind == 'ternary':
                value = rng.randrange(-1, 2)
            elif kind == 'rare_outliers':
                value = (i // 1280) % 31 + 1 if i % 1280 < 16 else 0
            numerator, denominator = case['gain']
            value = round_ratio(value * numerator, denominator)
            quantum = case['quantization_step']
            value = round_ratio(value, quantum) * quantum + case['dc']
            value = max(-32768, min(32767, value))
            if channel == 1 and case.get('right_channel') == 'silence':
                value = 0
            samples.append(value)
        per_channel.append(samples)
    values = [per_channel[channel][frame] for frame in range(count) for channel in range(channels)]
    if kind == 'middle_constant':
        width = (rate * 80 + 999) // 1000
        first = cut - overlap + (overlap - width) // 2
        for i in range(first * channels, (first + width) * channels):
            values[i] = 0
    reference = encode(values)
    if case.get('chain_fragments'):
        ends = [rate] + [rate + i * 1001 for i in range(1, case['chain_fragments'])]
        ranges = [(0, ends[0])] + [(previous - overlap, end) for previous, end in zip(ends, ends[1:])]
        pieces = [reference[a * channels * 2:b * channels * 2] for a, b in ranges]
        return pieces, [overlap] * (len(pieces) - 1), reference[:ends[-1] * channels * 2]
    pieces = [reference[:cut * channels * 2], reference[(cut - overlap) * channels * 2:]]
    transform = case.get('right_transform')
    if transform:
        right_values = values[(cut - overlap) * channels:]
        rng = random.Random(case['seed'] ^ 0x9E3779B97F4A7C15)
        if transform == 'dither':
            right_values = [max(-32768, min(32767, value + rng.choice([-1, 1]))) for value in right_values]
        elif transform == 'quantize':
            right_values = [max(-32768, min(32767, round_ratio(value, 8) * 8)) for value in right_values]
        elif transform == 'independent':
            right_values = [rng.randrange(-12000, 12001) for _ in right_values]
        elif transform == 'insert':
            position = overlap // 2 * channels
            right_values[position:position] = [123] * channels
        elif transform == 'delete':
            position = overlap // 2 * channels
            del right_values[position:position + channels]
        elif transform == 'one_channel':
            for i in range(1, len(right_values), channels):
                right_values[i] += 1
        pieces[1] = encode(right_values)
    physical_overlap = overlap if case['physical_truth'] == 'same_source_overlap' else 0
    return pieces, [physical_overlap], reference if physical_overlap else None
